test('tahsilat, müşteri bakiyesi, filtre ve kalıcılık',async({page},info)=>{
 await page.goto('/');
 await page.getByLabel('Kullanıcı adı',{exact:true}).fill('e2e-admin');
 await page.getByLabel('Parola',{exact:true}).fill('E2E-only-password-42');
 await page.getByRole('button',{name:'Giriş yap',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Genel bakış.'})).toBeVisible();
 const before=(await (await page.request.get('/api/customer-balances')).json()).find((b:{id:number})=>b.id===1);
 if(info.project.name==='mobile') await page.getByRole('button',{name:'Menüyü aç'}).click();
 await page.getByRole('button',{name:'Tahsilat ve bakiyeler',exact:true}).click();
 await expect(page.getByText('Müşterisi belirtilmeyen eski tahsilat toplamı:',{exact:false})).toBeVisible();
 await page.getByLabel('Müşteriye göre filtrele',{exact:true}).selectOption('1');
 await page.getByRole('button',{name:'Tahsilat ekle',exact:true}).click();
 await expect(page.getByLabel('Tahsilat müşterisi',{exact:true})).toHaveValue('1');
 await page.getByLabel('Tutar (₺)',{exact:true}).fill('12.35');
 await page.getByLabel('Tahsilat yöntemi',{exact:true}).selectOption('transfer');
 const note='Örnek tahsilat '+info.project.name;
 await page.getByLabel('Açıklama (isteğe bağlı)',{exact:true}).fill(note);
 await page.getByRole('button',{name:'Tahsilatı kaydet',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'Tahsilat kaydedildi'})).toBeVisible();
 await expect(page.getByText(note,{exact:true})).toBeVisible();
 const after=(await (await page.request.get('/api/customer-balances')).json()).find((b:{id:number})=>b.id===1);
 expect(after.balance_cents).toBe(before.balance_cents-1235);
 expect(after.collected_cents).toBe(before.collected_cents+1235);
 await page.reload();
 if(info.project.name==='mobile') await page.getByRole('button',{name:'Menüyü aç'}).click();
 await page.getByRole('button',{name:'Tahsilat ve bakiyeler',exact:true}).click();
 await page.getByLabel('Müşteriye göre filtrele',{exact:true}).selectOption('1');
 await expect(page.getByText(note,{exact:true})).toBeVisible();
 await page.getByLabel('Müşteriye göre filtrele',{exact:true}).selectOption('2');
 await expect(page.getByText(note,{exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:info.outputPath('collections.png'),fullPage:true});
});
