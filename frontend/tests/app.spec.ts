import {test,expect} from '@playwright/test';
test('panel, müşteri ve ürün ekleme; arama ve kalıcılık',async({page},info)=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Genel bakış.'})).toBeVisible();
 await expect(page.getByText('Günlük satış',{exact:true})).toBeVisible();
 await expect(page.getByText('Örnek Bahar Market',{exact:true})).toBeVisible();
 await page.screenshot({path:`/tmp/doga-${info.project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'Yeni müşteri',exact:true}).click();
 await page.getByLabel('Firma adı').fill('Örnek E2E '+info.project.name);
 await page.getByLabel('Yetkili kişi').fill('Demo Test');
 await page.getByLabel('İlçe / Bölge').fill('Kadıköy');
 await page.getByRole('button',{name:'Kaydet',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Müşteri başarıyla eklendi');
 await page.getByRole('button',{name:'Müşterileri görüntüle',exact:true}).click();
 await page.getByRole('textbox',{name:'Listede ara'}).fill('Örnek E2E '+info.project.name);
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await page.reload();
 await page.getByRole('button',{name:'Yeni ürün',exact:true}).click();
 await page.getByLabel('Ürün adı').fill('Örnek E2E Ürün '+info.project.name);
 await page.getByLabel('Ürün kodu').fill('E2E-'+info.project.name+'-'+Date.now());
 await page.getByLabel('Kategori',{exact:true}).fill('Bakliyat');
 await page.getByLabel('Birim fiyat').fill('42.75');
 await page.getByLabel('Stok (adet)').fill('25');
 await page.getByRole('button',{name:'Kaydet',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Ürün başarıyla eklendi');
 await page.getByRole('button',{name:'Tüm ürünleri görüntüle'}).click();
 await page.getByRole('textbox',{name:'Listede ara'}).fill('Örnek E2E Ürün '+info.project.name);
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await expect(page.locator('tbody')).toContainText('42,75');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.reload();
 await page.getByRole('button',{name:'Tüm ürünleri görüntüle'}).click();
 await expect(page.getByText('Örnek E2E Ürün '+info.project.name,{exact:true})).toBeVisible();
});
