 await expect(row).toContainText('İptal edildi');
 await expect(row).toContainText('Örnek test iptali');
 await expect(row.getByRole('button',{name:'İptal et',exact:true})).toHaveCount(0);
 const restored=(await (await page.request.get('/api/products')).json()).find((p:{id:number})=>p.id===1);
 expect(restored.stock).toBe(before.stock);
 await page.screenshot({path:info.outputPath('cancelled-order.png'),fullPage:true});
 await page.reload();
 if(info.project.name==='mobile') await page.getByRole('button',{name:'Menüyü aç'}).click();
 await page.getByRole('button',{name:'Siparişler',exact:true}).click();
 await expect(page.locator('tbody tr').first()).toContainText('İptal edildi');
 await expect(page.locator('tbody tr').first()).toContainText('Örnek test iptali');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
